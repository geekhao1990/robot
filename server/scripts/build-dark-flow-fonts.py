"""Emit the bundled 1-day chart font stylesheet (requires fonttools).

Usage: python build-dark-flow-fonts.py D-DIN.ttf NotoSansSC-VF.ttf
The caller saves stdout as miniprogram/styles/dark-flow-fonts.wxss.
Only chart glyphs are retained; no installed proprietary fonts are bundled.
"""
import base64
import io
import sys
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont


def face(source, family, weight, text):
    font = TTFont(source, recalcTimestamp=False)
    options = subset.Options()
    options.name_IDs = [0, 1, 2, 3, 4, 6, 13, 14, 16, 17]
    options.name_languages = ['*']
    options.layout_features = []
    sub = subset.Subsetter(options=options)
    sub.populate(text=text)
    sub.subset(font)
    if 'fvar' in font:
        font = instantiateVariableFont(font, {'wght': weight}, inplace=True)
    # Modified subsets must not use the upstream reserved font names.
    names = {1: family, 2: str(weight), 3: family + '-' + str(weight),
             4: family + ' ' + str(weight), 6: family + '-' + str(weight),
             16: family, 17: str(weight)}
    for record in font['name'].names:
        if record.nameID in names:
            record.string = names[record.nameID].encode(record.getEncoding())
    font.flavor = 'woff'
    output = io.BytesIO()
    font.save(output)
    encoded = base64.b64encode(output.getvalue()).decode('ascii')
    return ('@font-face { font-family: "' + family + '"; font-style: normal; '
            'font-weight: ' + str(weight) + '; src: url("data:font/woff;base64,'
            + encoded + '") format("woff"); }')


if __name__ == '__main__':
    numeric, chinese = sys.argv[1:3]
    print('/* Generated by server/scripts/build-dark-flow-fonts.py. '
          'OFL-1.1: see miniprogram/styles/font-licenses/. */')
    print(face(numeric, 'DarkFlowDigits', 400, '0123456789+-. '))
    for weight in [400, 700]:
        print(face(chinese, 'DarkFlowLabels', weight, '主力净流入散户明暗盘'))
